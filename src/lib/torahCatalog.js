export const verses = [...rishon, ...sheni, ...shelishi].map((verse) => ({
  ...verse,
  key: `bereshit:vayetzei:${verse.aliyahId.replace('vayetzei-','')}:${verse.chapter}:${verse.n}`
}));

verses.push(...kiTetse);

export const DEFAULT_SELECTION = { seferId:'bereshit', parashaId:'vayetzei', aliyahId:'vayetzei-rishon' };
export const SELECTION_STORAGE_KEY = 'torah-practice-selection-v1';

export function getSefer(id) { return sefarim.find((item) => item.id === id) || null; }
export function getParasha(id) { return parashiot.find((item) => item.id === id) || null; }
export function getAliyah(id) { return aliyot.find((item) => item.id === id) || null; }
export function getParashiotForSefer(seferId) { return parashiot.filter((item) => item.seferId === seferId).sort((a,b)=>a.order-b.order); }
export function getAliyotForParasha(parashaId) { return aliyot.filter((item) => item.parashaId === parashaId).sort((a,b)=>a.order-b.order); }
export function getVersesForAliyah(aliyahId) { return verses.filter((item) => item.aliyahId === aliyahId); }
export function getVerseByKey(key) { return verses.find((item) => item.key === key) || null; }

export function loadSelection() {
  try {
    const parsed = JSON.parse(localStorage.getItem(SELECTION_STORAGE_KEY) || 'null');
    if (parsed && getSefer(parsed.seferId) && getParasha(parsed.parashaId) && getAliyah(parsed.aliyahId)) return parsed;
  } catch {}
  return { ...DEFAULT_SELECTION };
}

export function saveSelection(selection) {
  const next = { ...DEFAULT_SELECTION, ...selection };
  try { localStorage.setItem(SELECTION_STORAGE_KEY, JSON.stringify(next)); } catch {}
  return next;
}

export function scrollText(tikkun) {
  return tikkun.normalize('NFD').replace(/[\u0591-\u05BD\u05BF-\u05C7]/g, '').replace(/[׃־׀]/g, ' ').replace(/\s+/g, ' ').trim();
}

export function storagePrefixForVerse(verse) {
  if (verse.aliyahId === 'vayetzei-rishon' && verse.chapter === 28) return `vayetsei/rishon/verse-${verse.n}`;
  return `torah/${verse.key.replaceAll(':','/')}`;
}
